"""Generate docs/METRICS.md from the roadmap and metric classes, so the documentation cannot drift from the code."""

from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from apps.evaluation.services.evaluator_registry import load_all_metrics
from apps.evaluation.services.roadmap import ROADMAP, STAGES


class Command(BaseCommand):
    help = "Write docs/METRICS.md from the registered metrics"

    def handle(self, *args, **options):
        registry = load_all_metrics()
        lines = [
            "# The 37 metrics",
            "",
            "In the recommended learning order. Generated by `python manage.py export_metrics_doc`. Do not edit by hand.",
            "",
            "**Per question:** scored for each question, then averaged. **Per run:** one number for the whole run.",
            "",
        ]
        for category, title, goal in STAGES:
            lines += [
                f"## {title}",
                "",
                goal,
                "",
                "| # | Metric | Priority | What you need to understand | Formula | Better | Scope |",
                "|---|--------|----------|-----------------------------|---------|--------|-------|",
            ]
            for order, (name, display_name, priority, question) in enumerate(ROADMAP, start=1):
                evaluator = registry.evaluators[name]
                if evaluator.category != category:
                    continue
                better = "Higher" if evaluator.higher_is_better else "Lower"
                scope = "Per question" if evaluator.scope == "case" else "Per run"
                lines.append(f"| {order} | {display_name} | {priority} | {question} | {evaluator.formula} | {better} | {scope} |")
            lines.append("")
        path = Path(settings.BASE_DIR) / "docs" / "METRICS.md"
        path.write_text("\n".join(lines))
        self.stdout.write(self.style.SUCCESS(f"Wrote {path} ({len(ROADMAP)} metrics)"))
